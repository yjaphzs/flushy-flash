/**
 * Post-prebuild configuration for the generated Android project.
 *
 * `expo prebuild` regenerates `android/` from scratch and `--clean` wipes it, so
 * neither of the settings below can be committed — they have to be re-applied
 * every time. Both exist because Gradle reads them from the *process*
 * environment, which is exactly what goes wrong on a freshly-configured machine:
 * a terminal opened before ANDROID_HOME/JAVA_HOME were set inherits neither, and
 * the resulting errors point at the wrong thing.
 *
 *   1. android/local.properties -> sdk.dir
 *      Without ANDROID_HOME in the shell, Gradle fails with "SDK location not
 *      found... define ANDROID_HOME" — accurate, but misleading when the variable
 *      IS set, just not in that process.
 *
 *   2. android/gradle.properties -> org.gradle.java.home
 *      gradlew falls back to whatever `java` is on PATH when JAVA_HOME is absent.
 *      On Windows that is usually the Oracle javapath shim pointing at the newest
 *      JDK. React Native 0.86 declares jvmToolchain(17), and on JDK 22+ the CMake
 *      configure tasks fail with:
 *
 *        Execution failed for task ':react-native-worklets:configureCMakeDebug[...]'
 *        > WARNING: A restricted method in java.lang.System has been called
 *
 *      which names neither Java nor the version. Verified directly: the identical
 *      gradle invocation fails on JDK 24 and succeeds on JDK 17.
 *
 * Runs automatically as part of `npm run prebuild`. Safe to run standalone.
 */

import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { spawnSync } from 'node:child_process';
import { resolve, join } from 'node:path';

const ANDROID_DIR = resolve(process.cwd(), 'android');

/** Gradle reads these as Java properties: "\" escapes and ":" separates. */
const escapeProperty = (p) => p.replace(/\\/g, '\\\\').replace(/:/g, '\\:');

if (!existsSync(ANDROID_DIR)) {
  // prebuild has not run yet. Not an error.
  process.exit(0);
}

// ── 1. SDK location ──────────────────────────────────────────────────────────

const sdkCandidates = [
  process.env.ANDROID_HOME,
  process.env.ANDROID_SDK_ROOT,
  process.platform === 'win32' ? join(process.env.LOCALAPPDATA ?? '', 'Android', 'Sdk') : null,
  process.platform === 'darwin' ? join(homedir(), 'Library', 'Android', 'sdk') : null,
  process.platform === 'linux' ? join(homedir(), 'Android', 'Sdk') : null,
].filter(Boolean);

// platform-tools is the marker of a real SDK; an empty Android/Sdk folder is a
// common leftover that would otherwise fail later and less clearly.
const sdk = sdkCandidates.find((p) => existsSync(join(p, 'platform-tools')));

if (sdk) {
  writeFileSync(
    join(ANDROID_DIR, 'local.properties'),
    `# Generated by scripts/configure-android-build.mjs — do not commit.\nsdk.dir=${escapeProperty(sdk)}\n`,
    'utf8',
  );
  console.log(`  local.properties  sdk.dir = ${sdk}`);
} else {
  console.warn(
    `\n  Could not locate an Android SDK (looked at: ${sdkCandidates.join(', ')}).\n` +
      '  Install it via Android Studio, then set ANDROID_HOME.\n',
  );
}

// ── 2. Pin the JDK ───────────────────────────────────────────────────────────

/** Major version of a JDK install. */
function javaMajor(javaHome) {
  if (!javaHome) return null;

  // Prefer the `release` file: it is a plain key=value manifest every JDK ships,
  // so this needs no subprocess at all.
  const releaseFile = join(javaHome, 'release');
  if (existsSync(releaseFile)) {
    const version = /^JAVA_VERSION="?(\d+)/m.exec(readFileSync(releaseFile, 'utf8'))?.[1];
    if (version) return Number.parseInt(version, 10);
  }

  // Fallback: ask java itself. Note it prints the version to STDERR and exits 0,
  // so execFileSync (which returns stdout only) sees nothing — spawnSync is
  // required to read both streams.
  const bin = join(javaHome, 'bin', process.platform === 'win32' ? 'java.exe' : 'java');
  if (!existsSync(bin)) return null;
  const proc = spawnSync(bin, ['-version'], { encoding: 'utf8' });
  const output = `${proc.stdout ?? ''}${proc.stderr ?? ''}`;
  return Number.parseInt(/version "(\d+)/.exec(output)?.[1] ?? '', 10) || null;
}

/** Directories that commonly hold JDK installs, per platform. */
function jdkSearchRoots() {
  if (process.platform === 'win32') {
    return ['C:\\Program Files\\Eclipse Adoptium', 'C:\\Program Files\\Java', 'C:\\Program Files\\Microsoft'];
  }
  if (process.platform === 'darwin') return ['/Library/Java/JavaVirtualMachines'];
  return ['/usr/lib/jvm'];
}

const REQUIRED_MAJOR = 17; // matches react-native's jvmToolchain(17)

function findJdk17() {
  if (process.env.JAVA_HOME && javaMajor(process.env.JAVA_HOME) === REQUIRED_MAJOR) {
    return process.env.JAVA_HOME;
  }
  for (const root of jdkSearchRoots()) {
    if (!existsSync(root)) continue;
    for (const entry of readdirSync(root)) {
      // macOS nests the real home inside the bundle.
      const candidates = [join(root, entry), join(root, entry, 'Contents', 'Home')];
      for (const c of candidates) {
        if (existsSync(c) && javaMajor(c) === REQUIRED_MAJOR) return c;
      }
    }
  }
  return null;
}

const jdk = findJdk17();
const gradleProps = join(ANDROID_DIR, 'gradle.properties');

if (jdk && existsSync(gradleProps)) {
  const line = `org.gradle.java.home=${escapeProperty(jdk)}`;
  let contents = readFileSync(gradleProps, 'utf8');

  if (/^org\.gradle\.java\.home=/m.test(contents)) {
    contents = contents.replace(/^org\.gradle\.java\.home=.*$/m, line);
  } else {
    contents +=
      `\n# Pinned by scripts/configure-android-build.mjs.\n` +
      `# RN 0.86 declares jvmToolchain(17); on JDK 22+ the CMake configure tasks\n` +
      `# fail with "A restricted method in java.lang.System has been called".\n` +
      `${line}\n`;
  }

  writeFileSync(gradleProps, contents, 'utf8');
  console.log(`  gradle.properties org.gradle.java.home = ${jdk}`);
} else if (!jdk) {
  const current = process.env.JAVA_HOME ? javaMajor(process.env.JAVA_HOME) : null;
  console.warn(
    `\n  No JDK ${REQUIRED_MAJOR} found${current ? ` (JAVA_HOME is JDK ${current})` : ''}.\n` +
      '  React Native 0.86 needs it; newer JDKs fail the CMake configure tasks.\n' +
      '    winget install -e --id EclipseAdoptium.Temurin.17.JDK\n',
  );
}
