const { withAppBuildGradle } = require('@expo/config-plugins');

/**
 * Injects a real release signing config into the generated Android project.
 *
 * Why this exists: Expo's bare template points `buildTypes.release` at
 * `signingConfigs.debug` — a release build is debug-signed out of the box. The
 * debug keystore is a well-known shared key, and worse, an APK signed with it
 * cannot be upgraded in place by one signed with a real key. Students would hit
 * INSTALL_FAILED_UPDATE_INCOMPATIBLE on their next update with no way out but to
 * uninstall and lose local state.
 *
 * Why a config plugin rather than patching android/ after prebuild: android/ is
 * gitignored and regenerated by `expo prebuild --clean` on every release build.
 * Post-hoc patching of generated files is exactly what CNG exists to avoid.
 *
 * The plugin is a no-op unless ANDROID_KEYSTORE_PATH is set, so local debug
 * builds work with no secrets and no configuration.
 */
const withReleaseSigning = (config) =>
  withAppBuildGradle(config, (cfg) => {
    const keystorePath = process.env.ANDROID_KEYSTORE_PATH;
    if (!keystorePath) return cfg;

    if (cfg.modResults.language !== 'groovy') {
      throw new Error('with-release-signing: expected a groovy build.gradle');
    }

    let contents = cfg.modResults.contents;

    if (contents.includes('flushyFlashRelease')) return cfg;

    // Values come from the environment so nothing secret is ever written into a
    // file that could be committed or cached.
    const releaseConfig = `
        flushyFlashRelease {
            storeFile file(System.getenv("ANDROID_KEYSTORE_PATH"))
            storePassword System.getenv("ANDROID_KEYSTORE_PASSWORD")
            keyAlias System.getenv("ANDROID_KEY_ALIAS")
            keyPassword System.getenv("ANDROID_KEY_PASSWORD")
        }
`;

    // 1. Add the signing config alongside the template's `debug` one.
    const anchor = 'signingConfigs {';
    if (!contents.includes(anchor)) {
      throw new Error('with-release-signing: no signingConfigs block found');
    }
    contents = contents.replace(anchor, `${anchor}${releaseConfig}`);

    // 2. Repoint the release build type. The template ships
    //    `signingConfig signingConfigs.debug` inside BOTH debug and release, so
    //    target the one that follows the `release {` marker specifically.
    const releaseBlock = /(release\s*\{[\s\S]*?)signingConfig signingConfigs\.debug/;
    if (!releaseBlock.test(contents)) {
      throw new Error('with-release-signing: release build type not in expected shape');
    }
    contents = contents.replace(releaseBlock, '$1signingConfig signingConfigs.flushyFlashRelease');

    cfg.modResults.contents = contents;
    return cfg;
  });

module.exports = withReleaseSigning;
